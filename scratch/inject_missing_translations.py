count = 0
for lang in all_lang_codes:
    pattern = rf"('{lang}':\s*\{{)"
    m = re.search(pattern, text)
    if not m:
        continue
    
    # build additions for this language
    additions = []
    for key, trans_map in new_translations.items():
        if key == 'thanks_journey':
            continue
        val = trans_map.get(lang, trans_map.get('en', ''))
        # escape single quotes
        val_escaped = val.replace("'", "\\'")
        additions.append(f"      '{key}': '{val_escaped}',\n")
    
    # Also check if thanks_journey needs override for this language
    if lang in new_translations['thanks_journey']:
        val = new_translations['thanks_journey'][lang]
        val_escaped = val.replace("'", "\\'").replace("\n", "\\n")
        # replace existing thanks_journey in this lang block
        # Find the block bounds
        start_idx = m.end()
        # Find matching close brace
        end_idx = text.find("    },", start_idx)
        if end_idx != -1:
            block = text[start_idx:end_idx]
            block_sub = re.sub(r"'thanks_journey':\s*'[^']+',?", f"'thanks_journey': '{val_escaped}',", block)
            text = text[:start_idx] + block_sub + text[end_idx:]

    # Inject the new keys right after `'{lang}': {`
    injection = "\n" + "".join(additions)
    text = re.sub(pattern, rf"\1{injection}", text, count=1)
    count += 1

with open('lib/localization/screen_translations.dart', 'w', encoding='utf-8') as f:
    f.write(text)

print(f"Successfully updated screen_translations.dart for {count} languages!")
