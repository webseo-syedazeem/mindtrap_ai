# -*- coding: utf-8 -*-
import json
import re

file_path = 'lib/localization/screen_translations.dart'
with open(file_path, 'r', encoding='utf-8') as f:
    orig_code = f.read()

# Pattern to extract language blocks
# In orig_code, each language is `'code': { ... },`
# Because some entries might have had raw newlines or broken lines, let's normalize raw newlines inside values
# But even better: let's parse each language block carefully.

# Let's see the list of all 56 language codes
LANG_CODES = [
    'en', 'ur', 'hi', 'bn', 'te', 'mr', 'ta', 'gu', 'kn', 'ml', 'pa', 'or', 'as', 'sa', 'ne', 'si',
    'ar', 'fa', 'ps', 'sd', 'es', 'fr', 'de', 'it', 'pt_BR', 'pt_PT', 'ru', 'tr', 'zh_CN', 'zh_TW',
    'ja', 'ko', 'id', 'vi', 'th', 'ms', 'fil', 'my', 'km', 'nl', 'pl', 'sv', 'uk', 'el', 'cs', 'ro',
    'hu', 'da', 'fi', 'no', 'he', 'sw', 'am', 'ha', 'yo', 'zu'
]

# Let's extract existing keys per language using line-by-line scanning
all_langs = {code: {} for code in LANG_CODES}
current_lang = None
current_key = None
current_val = []

lines = orig_code.splitlines()
for line in lines:
    stripped = line.strip()
    # Check if starting a language
    m_lang = re.match(r"^'([a-zA-Z_]+)':\s*\{", stripped)
    if m_lang and m_lang.group(1) in LANG_CODES:
        current_lang = m_lang.group(1)
        current_key = None
        current_val = []
        continue

    if stripped.startswith('},') or stripped == '}':
        if current_lang and current_key:
            val_str = "\n".join(current_val).strip()
            # strip trailing comma and quote
            if val_str.endswith(','):
                val_str = val_str[:-1].strip()
            if val_str.startswith("'") and val_str.endswith("'"):
                val_str = val_str[1:-1]
            elif val_str.startswith('"') and val_str.endswith('"'):
                val_str = val_str[1:-1]
            all_langs[current_lang][current_key] = val_str
            current_key = None
            current_val = []
        current_lang = None
        continue

    if current_lang is not None:
        # Check if line starts a new key: 'key': '...
        m_kv = re.match(r"^'([a-zA-Z0-9_]+)':\s*(.*)$", stripped)
        if m_kv:
            # save previous key if any
            if current_key:
                val_str = "\n".join(current_val).strip()
                if val_str.endswith(','):
                    val_str = val_str[:-1].strip()
                if val_str.startswith("'") and val_str.endswith("'"):
                    val_str = val_str[1:-1]
                elif val_str.startswith('"') and val_str.endswith('"'):
                    val_str = val_str[1:-1]
                all_langs[current_lang][current_key] = val_str

            current_key = m_kv.group(1)
            rem = m_kv.group(2)
            current_val = [rem]
        else:
            if current_key:
                current_val.append(stripped)

print(f"Extracted languages: {len(all_langs)}")
for c in ['en', 'ur', 'pa', 'hi']:
    print(f"[{c}] keys count: {len(all_langs[c])}")

# Clean up corrupted backslashes from previous runs
for c in all_langs:
    for k, v in list(all_langs[c].items()):
        # Replace runaway backslashes
        if 'TODAY' in v and '\\' in v:
            all_langs[c][k] = "TODAY'S NEW PUZZLE IS LIVE"
        elif 'Today' in v and '\\' in v:
            if 'MindTrap' in v or k == 'todays_mindtrap':
                all_langs[c][k] = "Today's MindTrap"
            elif 'Solved' in v or k == 'todays_puzzle_solved':
                all_langs[c][k] = "Today's Puzzle Solved! 🎉"
            elif 'Claimed' in v or k == 'daily_reward_claimed':
                all_langs[c][k] = "Today's Reward Claimed ✓ (+20 Coins)"
            else:
                all_langs[c][k] = v.replace('\\\\\\\\', '').replace('\\\\', '')
        # Remove any lingering trailing backslashes at end of string
        all_langs[c][k] = re.sub(r'\\+$', '', all_langs[c][k])

